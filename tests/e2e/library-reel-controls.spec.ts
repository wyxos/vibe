import { expect, test } from '@playwright/test'
import type {} from '../browser/harness'

for (const width of [1440, 390]) {
  test.describe(`native reel controls at ${width}px`, () => {
    test.use({ viewport: { width, height: 844 }, hasTouch: width < 700, isMobile: width < 700 })
    for (const kind of ['video', 'audio']) {
      test(`${kind} controls idle, stay hidden on navigation, and reveal on input`, async ({ page }) => {
        const errors: string[] = []
        page.on('pageerror', error => errors.push(error.message))
        await page.goto(`/?scenario=${kind}&layout=reel`)
        const host = page.locator('.reel-media-controls-host')
        const controls = host.locator('.media-controls')
        await expect(controls).toBeVisible()
        const media = page.locator('.reel-item').first().locator(kind)
        await expect.poll(() => media.evaluate((element: HTMLMediaElement) => element.muted)).toBe(false)
        await page.clock.install()
        await page.clock.fastForward(4999)
        await expect(controls).not.toHaveClass(/idle-hidden/)
        await page.clock.fastForward(1)
        await expect(controls).toHaveClass(/idle-hidden/)
        await expect(controls).toHaveAttribute('inert', '')
        await expect(controls).toHaveCSS('pointer-events', 'none')
        if (width < 700) {
          await page.locator('.reel-item').first().locator('.media-card-media')
            .dispatchEvent('pointermove', { pointerType: 'touch', bubbles: true })
          await expect(controls).toHaveClass(/idle-hidden/)
        }
        await page.evaluate(() => window.__vibe.nextReelPost())
        await page.clock.runFor(350)
        await expect(controls).toHaveCount(1)
        await expect(controls).toHaveClass(/idle-hidden/)
        const reel = page.locator('.reel-feed')
        const postId = await reel.getAttribute('data-active-post-id')
        const active = reel.locator(`[data-post-id="${postId}"]`)
        if (width < 700) {
          const native = active.locator(kind)
          const paused = await native.evaluate((element: HTMLMediaElement) => element.paused)
          await active.locator(kind === 'audio' ? '.media-audio-artwork' : 'video').tap()
          expect(await native.evaluate((element: HTMLMediaElement) => element.paused)).toBe(paused)
        } else await active.locator('.media-card-media').hover()
        await expect(controls).not.toHaveClass(/idle-hidden/)
        await expect(controls).not.toHaveAttribute('inert', '')
        await host.getByRole('slider', { name: `Seek ${kind}` }).focus()
        await page.clock.fastForward(6000)
        await expect(controls).not.toHaveClass(/idle-hidden/)
        expect(errors).toEqual([])
      })
    }

    test('volume, timestamp and options use working native media controls', async ({ page }) => {
      await page.goto('/?scenario=video&layout=reel')
      const controls = page.locator('.reel-media-controls-host .media-controls')
      await expect(controls).toBeVisible()
      const native = page.locator('.reel-item').first().locator('video')
      if (width < 700) {
        const volumeToggle = controls.getByRole('button', { name: 'Video volume control', exact: true })
        await expect(controls.getByRole('slider', { name: 'Video volume', exact: true })).toBeHidden()
        await volumeToggle.tap()
        const volume = controls.getByRole('slider', { name: 'Video volume', exact: true })
        await expect(volume).toBeVisible()
        await expect(volume).toHaveCSS('writing-mode', 'vertical-lr')
        const box = await volume.boundingBox()
        expect(box!.height).toBeGreaterThan(box!.width * 4)
        await volume.fill('0.4')
        await expect.poll(() => native.evaluate((video: HTMLVideoElement) => video.volume)).toBe(0.4)
        await volume.press('Escape')
        await expect(volumeToggle).toBeFocused()
        await expect(volume).toBeHidden()
        const time = await controls.locator('.media-control-time').boundingBox()
        const frame = await controls.boundingBox()
        expect(Math.abs(time!.x + time!.width / 2 - frame!.x - frame!.width / 2)).toBeLessThan(1)
        const button = await volumeToggle.boundingBox()
        expect(button!.width).toBeGreaterThanOrEqual(44)
        await expect(volumeToggle.locator('svg')).toHaveCSS('width', '27px')
      }
      const options = controls.getByRole('button', { name: 'Video options', exact: true })
      await options.click()
      await controls.getByRole('button', { name: '1.5× speed', exact: true }).click()
      await expect.poll(() => native.evaluate((video: HTMLVideoElement) => video.playbackRate)).toBe(1.5)
      await expect(controls.getByRole('button', { name: '1.5× speed', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await controls.getByRole('button', { name: 'Mute', exact: true }).click()
      await expect.poll(() => native.evaluate((video: HTMLVideoElement) => video.muted)).toBe(true)
      await options.press('Escape')
      await expect(options).toHaveAttribute('aria-expanded', 'false')
      await expect(options).toBeFocused()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await expect(controls.locator('.media-control-playback')).toHaveCSS('background-color', 'rgba(8, 8, 8, 0.3)')
    })
  })
}

test('each feed-opened reel starts with visible controls after an idle close', async ({ page }) => {
  await page.goto('/?scenario=video&layout=masonry')
  const card = page.locator('.masonry-item').first()
  await card.click()
  const controls = page.locator('.vibe-reel-overlay .media-controls')
  await expect(controls).toBeVisible()
  await page.clock.install()
  await page.clock.fastForward(5000)
  await expect(controls).toHaveClass(/idle-hidden/)
  await page.keyboard.press('Tab')
  await expect(controls).not.toHaveClass(/idle-hidden/)
  await expect(controls.getByRole('slider', { name: 'Seek video' })).toBeFocused()
  await page.locator('.vibe-reel-overlay').focus()
  await page.clock.fastForward(5000)
  await expect(controls).toHaveClass(/idle-hidden/)
  await page.keyboard.press('Escape')
  await expect(page.locator('.vibe-reel-overlay')).toHaveCount(0)
  await card.click()
  await expect(controls).toBeVisible()
  await expect(controls).not.toHaveClass(/idle-hidden/)
})
