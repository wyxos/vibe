import { expect, test } from '@playwright/test'
import { capture, ready } from './showcaseSupport'

for (const width of [1440, 390]) test(`preview buttons activate their reel items at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 844 })
  if (width === 390) await page.emulateMedia({ reducedMotion: 'reduce' })
  const errors = await ready(page)
  await page.locator('.masonry-item .media-card-activator').first().click()
  await expect(page.locator('.vibe-reel-overlay')).toHaveAttribute('data-reel-entry', 'ready')
  await page.getByRole('button', { name: 'Upcoming previews', exact: true }).click()
  const count = width === 390 ? 14 : 4
  for (let index = 4; index < count; index++) {
    await page.getByRole('button', { name: 'More previews', exact: true }).click()
  }
  const feed = page.locator('.reel-feed')
  const previous = page.getByRole('button', { name: 'Previous previews', exact: true })
  const next = page.getByRole('button', { name: 'Next previews', exact: true })
  const cards = page.locator('.reel-preview-list [data-preview-post-id]')
  const activePost = await feed.getAttribute('data-active-post-id')
  await expect(previous).toBeHidden()
  await expect(next).toBeVisible()
  await expect(cards).toHaveCount(count)
  const postIds = () => cards.evaluateAll(elements => elements.map(element => element.getAttribute('data-preview-post-id')))
  const firstPage = await postIds()
  await next.click()
  const track = page.locator('.reel-preview-list')
  if (width !== 390) await expect(track).toHaveCSS('transform', /matrix/)
  await expect(cards).toHaveCount(width === 390 ? 3 : count)
  await expect.poll(async () => (await postIds()).every(id => !firstPage.includes(id))).toBe(true)
  const secondPage = await postIds()
  if (width === 390) await expect(next).toBeHidden()
  await expect(feed).toHaveAttribute('data-active-post-id', activePost!)
  await expect(track).toHaveCSS('transform', 'none')
  await previous.click()
  await expect.poll(postIds).toEqual(firstPage)
  await expect(feed).toHaveAttribute('data-active-post-id', activePost!)
  await next.click()
  await expect.poll(postIds).toEqual(secondPage)
  const preview = page.getByRole('button', { name: 'Open upcoming item 2', exact: true })
  const postId = await preview.locator('..').getAttribute('data-preview-post-id')
  if (width === 390) await preview.click()
  else await preview.press('Enter')
  await expect(feed).toHaveAttribute('data-active-post-id', postId!)
  await expect(feed).toBeFocused()
  await expect(feed).not.toHaveAttribute('data-transitioning', '')
  await expect(cards).toHaveCount(width === 390 ? 1 : count)
  await expect(page.locator('.reel-preview-list')).not.toContainText(/\+\d/)
  await expect(previous).toBeHidden()
  await capture(page, `vibe-preview-selection-${width}`)
  expect(errors).toEqual([])
})
